func TestGooseGeneratedIdentityTable(t *testing.T) {
	eng := memengine.New()
	_ = eng.Open("")
	defer eng.Close()

	cat := catalog.New(eng)
	coord := NewCoordinator(cat, eng, Config{})

	// 1. Exact Goose PostgreSQL migration history table DDL
	ddl := `
	CREATE TABLE goose_db_version (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NULL DEFAULT now()
	);`
	if _, err := coord.ExecuteSQL(ddl); err != nil {
		t.Fatalf("failed to create goose_db_version table: %v", err)
	}

	tbl, err := eng.GetTable("goose_db_version")
	if err != nil {
		t.Fatalf("failed to retrieve table schema: %v", err)
	}

	idCol, _, found := tbl.FindColumn("id")
	if !found || idCol == nil {
		t.Fatalf("id column not found in table schema")
	}
	if !idCol.Identity {
		t.Errorf("expected id column to be marked as Identity, got false")
	}
	if idCol.Default != "" {
		t.Errorf("expected id column Default to be empty, got %q (should not be 'AS')", idCol.Default)
	}

	// 2. Insert multiple goose migration version rows without specifying 'id'
	ins1 := `INSERT INTO goose_db_version (version_id, is_applied) VALUES (1, true);`
	if res, err := coord.ExecuteSQL(ins1); err != nil {
		t.Fatalf("failed to insert initial goose version: %v", err)
	} else if res.RowsAffected != 1 {
		t.Fatalf("expected 1 row affected, got %d", res.RowsAffected)
	}

	ins2 := `INSERT INTO goose_db_version (version_id, is_applied) VALUES (2, true);`
	if res, err := coord.ExecuteSQL(ins2); err != nil {
		t.Fatalf("failed to insert second goose version (duplicate key 'AS' regression): %v", err)
	} else if res.RowsAffected != 1 {
		t.Fatalf("expected 1 row affected, got %d", res.RowsAffected)
	}

	// 3. Query back rows and verify auto-increment sequence 1, 2
	sel := `SELECT id, version_id, is_applied FROM goose_db_version ORDER BY id ASC;`
	qRes, err := coord.ExecuteSQL(sel)
	if err != nil {
		t.Fatalf("failed to select goose_db_version rows: %v", err)
	}
	if len(qRes.Rows) != 2 {
		t.Fatalf("expected 2 rows, got %d", len(qRes.Rows))
	}

	v1 := fmt.Sprintf("%v", qRes.Rows[0]["id"])
	v2 := fmt.Sprintf("%v", qRes.Rows[1]["id"])
	if v1 != "1" || v2 != "2" {
		t.Errorf("expected id sequence 1, 2; got %s, %s", v1, v2)
	}
}

func TestGeneratedAlwaysIdentityVariants(t *testing.T) {
	eng := memengine.New()
	_ = eng.Open("")
	defer eng.Close()

	cat := catalog.New(eng)
	coord := NewCoordinator(cat, eng, Config{})

	ddl := `
	CREATE TABLE test_always_ident (
		item_id bigint PRIMARY KEY GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 1),
		name varchar(100) NOT NULL DEFAULT 'test'
	);`
	if _, err := coord.ExecuteSQL(ddl); err != nil {
		t.Fatalf("failed to create test_always_ident table: %v", err)
	}

	tbl, err := eng.GetTable("test_always_ident")
	if err != nil {
		t.Fatalf("failed to get table: %v", err)
	}
	col, _, _ := tbl.FindColumn("item_id")
	if col == nil || !col.Identity || col.Default != "" {
		t.Fatalf("invalid column metadata: %+v", col)
	}

	nameCol, _, _ := tbl.FindColumn("name")
	if nameCol == nil || (nameCol.Default != "test" && nameCol.Default != "'test'") {
		t.Fatalf("expected name column default 'test', got %q", nameCol.Default)
	}
}

func TestInsertDefaultOmittedColumn(t *testing.T) {
	eng := memengine.New()
	_ = eng.Open("")
	defer eng.Close()

	cat := catalog.New(eng)
	coord := NewCoordinator(cat, eng, Config{})

	ddl := `
	CREATE TABLE inventories_test (
		item_id VARCHAR(64) PRIMARY KEY,
		warehouse_id VARCHAR(64) NOT NULL DEFAULT 'wh_default',
		quantity INT
	);`
	if _, err := coord.ExecuteSQL(ddl); err != nil {
		t.Fatalf("failed to create inventories_test table: %v", err)
	}

	ins := `INSERT INTO inventories_test (item_id, quantity) VALUES ('item-1', 100);`
	if res, err := coord.ExecuteSQL(ins); err != nil {
		t.Fatalf("insert failed: %v", err)
	} else if res.RowsAffected != 1 {
		t.Fatalf("expected 1 row affected, got %d", res.RowsAffected)
	}

	sel := `SELECT item_id, warehouse_id, quantity FROM inventories_test WHERE item_id = 'item-1';`
	res, err := coord.ExecuteSQL(sel)
	if err != nil {
		t.Fatalf("select failed: %v", err)
	}
	if len(res.Rows) != 1 {
		t.Fatalf("expected 1 row, got %d", len(res.Rows))
	}
	t.Logf("Result row: %+v", res.Rows[0])
	whID := fmt.Sprintf("%v", res.Rows[0]["warehouse_id"])
	if whID != "wh_default" {
		t.Errorf("expected warehouse_id 'wh_default', got %q", whID)
	}
}
