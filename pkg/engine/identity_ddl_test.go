func TestGooseGeneratedIdentityTable(t *testing.T) {
	eng := memengine.New()
	_ = eng.Open("")
	defer eng.Close()

	cat := catalog.New(eng)
	coord := NewCoordinator(cat, eng, Config{})

	// 1. Exact Goose PostgreSQL migration history table DDL
	ddl := `
	CREATE TABLE goose_db_version (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NULL DEFAULT now()
	);`
	if _, err := coord.ExecuteSQL(ddl); err != nil {
		t.Fatalf("failed to create goose_db_version table: %v", err)
	}

	tbl, err := eng.GetTable("goose_db_version")
	if err != nil {
		t.Fatalf("failed to retrieve table schema: %v", err)
	}

	idCol, _, found := tbl.FindColumn("id")
	if !found || idCol == nil {
		t.Fatalf("id column not found in table schema")
	}
	if !idCol.Identity {
		t.Errorf("expected id column to be marked as Identity, got false")
	}
	if idCol.Default != "" {
		t.Errorf("expected id column Default to be empty, got %q (should not be 'AS')", idCol.Default)
	}

	// 2. Insert multiple goose migration version rows without specifying 'id'
	ins1 := `INSERT INTO goose_db_version (version_id, is_applied) VALUES (1, true);`
	if res, err := coord.ExecuteSQL(ins1); err != nil {
		t.Fatalf("failed to insert initial goose version: %v", err)
	} else if res.RowsAffected != 1 {
		t.Fatalf("expected 1 row affected, got %d", res.RowsAffected)
	}

	ins2 := `INSERT INTO goose_db_version (version_id, is_applied) VALUES (2, true);`
	if res, err := coord.ExecuteSQL(ins2); err != nil {
		t.Fatalf("failed to insert second goose version (duplicate key 'AS' regression): %v", err)
	} else if res.RowsAffected != 1 {
		t.Fatalf("expected 1 row affected, got %d", res.RowsAffected)
	}

	// 3. Query back rows and verify auto-increment sequence 1, 2
	sel := `SELECT id, version_id, is_applied FROM goose_db_version ORDER BY id ASC;`
	qRes, err := coord.ExecuteSQL(sel)
	if err != nil {
		t.Fatalf("failed to select goose_db_version rows: %v", err)
	}
	if len(qRes.Rows) != 2 {
		t.Fatalf("expected 2 rows, got %d", len(qRes.Rows))
	}

	v1 := fmt.Sprintf("%v", qRes.Rows[0]["id"])
	v2 := fmt.Sprintf("%v", qRes.Rows[1]["id"])
	if v1 != "1" || v2 != "2" {
		t.Errorf("expected id sequence 1, 2; got %s, %s", v1, v2)
	}
}

func TestGeneratedAlwaysIdentityVariants(t *testing.T) {
	eng := memengine.New()
	_ = eng.Open("")
	defer eng.Close()

	cat := catalog.New(eng)
	coord := NewCoordinator(cat, eng, Config{})

	ddl := `
	CREATE TABLE test_always_ident (
		item_id bigint PRIMARY KEY GENERATED ALWAYS AS IDENTITY (START WITH 10 INCREMENT BY 1),
		name varchar(100) NOT NULL DEFAULT 'test'
	);`
	if _, err := coord.ExecuteSQL(ddl); err != nil {
		t.Fatalf("failed to create test_always_ident table: %v", err)
	}

	tbl, err := eng.GetTable("test_always_ident")
	if err != nil {
		t.Fatalf("failed to get table: %v", err)
	}
	col, _, _ := tbl.FindColumn("item_id")
	if col == nil || !col.Identity || col.Default != "" {
		t.Fatalf("invalid column metadata: %+v", col)
	}

	nameCol, _, _ := tbl.FindColumn("name")
	if nameCol == nil || (nameCol.Default != "test" && nameCol.Default != "'test'") {
		t.Fatalf("expected name column default 'test', got %q", nameCol.Default)
	}
}

func TestInsertDefaultOmittedColumn(t *testing.T) {
	eng := memengine.New()
	_ = eng.Open("")
	defer eng.Close()

	cat := catalog.New(eng)
	coord := NewCoordinator(cat, eng, Config{})

	ddl := `
	CREATE TABLE inventories_test (
		item_id VARCHAR(64) PRIMARY KEY,
		warehouse_id VARCHAR(64) NOT NULL DEFAULT 'wh_default',
		quantity INT
	);`
	if _, err := coord.ExecuteSQL(ddl); err != nil {
		t.Fatalf("failed to create inventories_test table: %v", err)
	}

	ins := `INSERT INTO inventories_test (item_id, quantity) VALUES ('item-1', 100);`
	if res, err := coord.ExecuteSQL(ins); err != nil {
		t.Fatalf("insert failed: %v", err)
	} else if res.RowsAffected != 1 {
		t.Fatalf("expected 1 row affected, got %d", res.RowsAffected)
	}

	sel := `SELECT item_id, warehouse_id, quantity FROM inventories_test WHERE item_id = 'item-1';`
	res, err := coord.ExecuteSQL(sel)
	if err != nil {
		t.Fatalf("select failed: %v", err)
	}
	if len(res.Rows) != 1 {
		t.Fatalf("expected 1 row, got %d", len(res.Rows))
	}
	t.Logf("Result row: %+v", res.Rows[0])
	whID := fmt.Sprintf("%v", res.Rows[0]["warehouse_id"])
	if whID != "wh_default" {
		t.Errorf("expected warehouse_id 'wh_default', got %q", whID)
	}
}

func TestTSQLIdentitySeedAndIncrement(t *testing.T) {
	eng := memengine.New()
	_ = eng.Open("")
	defer eng.Close()

	cat := catalog.New(eng)
	coord := NewCoordinator(cat, eng, Config{})
	defer coord.Close()

	// 1. Table with custom seed 100 and step 5
	ddl := `CREATE TABLE t_seed (id INT IDENTITY(100, 5) PRIMARY KEY, val VARCHAR(20));`
	if _, err := coord.ExecuteSQL(ddl); err != nil {
		t.Fatalf("create failed: %v", err)
	}

	tbl, err := eng.GetTable("t_seed")
	if err != nil {
		t.Fatalf("get table failed: %v", err)
	}
	idCol, ok := tbl.IdentityColumn()
	if !ok || idCol == nil {
		t.Fatalf("identity column not found")
	}
	if idCol.IdentitySeed != 100 || idCol.IdentityIncrement != 5 {
		t.Fatalf("expected seed=100, incr=5; got seed=%d, incr=%d", idCol.IdentitySeed, idCol.IdentityIncrement)
	}

	// 2. Metadata functions: IDENT_SEED, IDENT_INCR, IDENT_CURRENT before inserts
	res, err := coord.ExecuteSQL(`SELECT IDENT_SEED('t_seed') AS s, IDENT_INCR('t_seed') AS i, IDENT_CURRENT('t_seed') AS c;`)
	if err != nil {
		t.Fatalf("ident functions query failed: %v", err)
	}
	if len(res.Rows) != 1 {
		t.Fatalf("expected 1 row, got %d", len(res.Rows))
	}
	if fmt.Sprintf("%v", res.Rows[0]["s"]) != "100" || fmt.Sprintf("%v", res.Rows[0]["i"]) != "5" {
		t.Fatalf("expected s=100, i=5; got %+v", res.Rows[0])
	}

	// 3. First insert: should get id = 100
	if _, err := coord.ExecuteSQL(`INSERT INTO t_seed (val) VALUES ('first');`); err != nil {
		t.Fatalf("insert 1 failed: %v", err)
	}

	// 4. Second insert: should get id = 105
	if _, err := coord.ExecuteSQL(`INSERT INTO t_seed (val) VALUES ('second');`); err != nil {
		t.Fatalf("insert 2 failed: %v", err)
	}

	// 5. Multi-row insert: should get id = 110, 115
	if _, err := coord.ExecuteSQL(`INSERT INTO t_seed (val) VALUES ('third'), ('fourth');`); err != nil {
		t.Fatalf("insert 3-4 failed: %v", err)
	}

	res, err = coord.ExecuteSQL(`SELECT id, val FROM t_seed ORDER BY id ASC;`)
	if err != nil {
		t.Fatalf("select failed: %v", err)
	}
	if len(res.Rows) != 4 {
		t.Fatalf("expected 4 rows, got %d", len(res.Rows))
	}
	expectedIDs := []string{"100", "105", "110", "115"}
	for i, exp := range expectedIDs {
		actual := fmt.Sprintf("%v", res.Rows[i]["id"])
		if actual != exp {
			t.Errorf("row[%d] id: expected %s, got %s", i, exp, actual)
		}
	}

	// 6. Check IDENT_CURRENT after inserts
	res, err = coord.ExecuteSQL(`SELECT IDENT_CURRENT('t_seed') AS c;`)
	if err != nil {
		t.Fatalf("ident_current query failed: %v", err)
	}
	if fmt.Sprintf("%v", res.Rows[0]["c"]) != "115" {
		t.Errorf("expected IDENT_CURRENT = 115, got %v", res.Rows[0]["c"])
	}

	// 7. TRUNCATE TABLE t_seed RESTART IDENTITY
	if _, err := coord.ExecuteSQL(`TRUNCATE TABLE t_seed RESTART IDENTITY;`); err != nil {
		t.Fatalf("truncate failed: %v", err)
	}

	// 8. Insert after truncate: should restart at 100
	if _, err := coord.ExecuteSQL(`INSERT INTO t_seed (val) VALUES ('after_trunc');`); err != nil {
		t.Fatalf("insert after truncate failed: %v", err)
	}
	res, err = coord.ExecuteSQL(`SELECT id, val FROM t_seed;`)
	if err != nil {
		t.Fatalf("select after truncate failed: %v", err)
	}
	if len(res.Rows) != 1 || fmt.Sprintf("%v", res.Rows[0]["id"]) != "100" {
		t.Fatalf("expected 1 row with id=100 after truncate, got %+v", res.Rows)
	}

	// 9. Stored procedure execution inserting into table with custom identity
	spDDL := `CREATE PROCEDURE sp_seed_insert @v VARCHAR(20) AS
	BEGIN
		INSERT INTO t_seed (val) VALUES (@v);
	END;`
	if _, err := coord.ExecuteSQL(spDDL); err != nil {
		t.Fatalf("create proc failed: %v", err)
	}

	if _, err := coord.ExecuteSQL(`EXEC sp_seed_insert 'from_sp';`); err != nil {
		t.Fatalf("exec sp failed: %v", err)
	}
	res, err = coord.ExecuteSQL(`SELECT id, val FROM t_seed ORDER BY id ASC;`)
	if err != nil {
		t.Fatalf("select after sp failed: %v", err)
	}
	if len(res.Rows) != 2 || fmt.Sprintf("%v", res.Rows[1]["id"]) != "105" {
		t.Fatalf("expected row 2 with id=105 from SP, got %+v", res.Rows)
	}

	// 10. INSERT INTO t_seed (val) SELECT ... (verifying custom seed and increment in INSERT ... SELECT)
	if _, err := coord.ExecuteSQL(`CREATE TABLE src_data (val VARCHAR(20));`); err != nil {
		t.Fatalf("create src_data failed: %v", err)
	}
	if _, err := coord.ExecuteSQL(`INSERT INTO src_data VALUES ('sel_1'), ('sel_2');`); err != nil {
		t.Fatalf("insert src_data failed: %v", err)
	}
	if _, err := coord.ExecuteSQL(`INSERT INTO t_seed (val) SELECT val FROM src_data ORDER BY val ASC;`); err != nil {
		t.Fatalf("insert select failed: %v", err)
	}
	res, err = coord.ExecuteSQL(`SELECT id, val FROM t_seed ORDER BY id ASC;`)
	if err != nil {
		t.Fatalf("select after insert select failed: %v", err)
	}
	if len(res.Rows) != 4 {
		t.Fatalf("expected 4 rows after insert select, got %d", len(res.Rows))
	}
	if fmt.Sprintf("%v", res.Rows[2]["id"]) != "110" || fmt.Sprintf("%v", res.Rows[3]["id"]) != "115" {
		t.Errorf("expected ids 110, 115 from insert select; got row2=%v, row3=%v", res.Rows[2]["id"], res.Rows[3]["id"])
	}

	// 11. Multi-table isolation with independent custom seeds: t_seed_2 with seed 1000, step 50
	if _, err := coord.ExecuteSQL(`CREATE TABLE t_seed_2 (id INT IDENTITY(1000, 50) PRIMARY KEY, info VARCHAR(20));`); err != nil {
		t.Fatalf("create t_seed_2 failed: %v", err)
	}
	if _, err := coord.ExecuteSQL(`INSERT INTO t_seed_2 (info) VALUES ('first_2'), ('second_2');`); err != nil {
		t.Fatalf("insert t_seed_2 failed: %v", err)
	}
	res2, err := coord.ExecuteSQL(`SELECT id, info FROM t_seed_2 ORDER BY id ASC;`)
	if err != nil {
		t.Fatalf("select t_seed_2 failed: %v", err)
	}
	if len(res2.Rows) != 2 || fmt.Sprintf("%v", res2.Rows[0]["id"]) != "1000" || fmt.Sprintf("%v", res2.Rows[1]["id"]) != "1050" {
		t.Fatalf("expected t_seed_2 ids 1000, 1050; got %+v", res2.Rows)
	}
}
