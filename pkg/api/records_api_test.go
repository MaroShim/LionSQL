func TestAPI_AutoGeneratedRecordsREST(t *testing.T) {
	server := setupTestServer()

	// 1. Create a table "customers" via SQL DDL
	ddl := `
	CREATE TABLE customers (
		id INT PRIMARY KEY,
		name VARCHAR(100) NOT NULL,
		balance FLOAT NOT NULL,
		status VARCHAR(20) NOT NULL
	);
	`
	if _, err := server.ExecuteSQL(ddl); err != nil {
		t.Fatalf("failed to create customers table: %v", err)
	}

	handler := server.Handler()

	// 2. POST /api/records/:table - create records
	recordsToCreate := []map[string]any{
		{"id": 1, "name": "Alice", "balance": 1000.5, "status": "active"},
		{"id": 2, "name": "Bob", "balance": 450.0, "status": "pending"},
		{"id": 3, "name": "Charlie", "balance": 800.0, "status": "active"},
		{"id": 4, "name": "Diana", "balance": 200.0, "status": "inactive"},
	}

	for _, rec := range recordsToCreate {
		body, _ := json.Marshal(rec)
		req := httptest.NewRequest(http.MethodPost, "/api/records/customers", bytes.NewReader(body))
		req.Header.Set("Content-Type", "application/json")
		w := httptest.NewRecorder()
		handler.ServeHTTP(w, req)

		if w.Code != http.StatusCreated {
			t.Fatalf("POST /api/records/customers failed with code %d: %s", w.Code, w.Body.String())
		}

		var created map[string]any
		if err := json.Unmarshal(w.Body.Bytes(), &created); err != nil {
			t.Fatalf("failed to decode created record: %v", err)
		}
		if created["name"] != rec["name"] {
			t.Errorf("expected name %v, got %v", rec["name"], created["name"])
		}
	}

	// Also create one record with auto-generated ID (id omitted)
	autoReqBody := []byte(`{"name": "Evan", "balance": 600.0, "status": "active"}`)
	req := httptest.NewRequest(http.MethodPost, "/api/records/customers", bytes.NewReader(autoReqBody))
	req.Header.Set("Content-Type", "application/json")
	w := httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusCreated {
		t.Fatalf("POST with auto-generated ID failed with code %d: %s", w.Code, w.Body.String())
	}
	var autoCreated map[string]any
	_ = json.Unmarshal(w.Body.Bytes(), &autoCreated)
	if autoCreated["id"] == nil || autoCreated["name"] != "Evan" {
		t.Fatalf("expected auto-generated id, got: %+v", autoCreated)
	}

	// 3. User request exact query:
	// GET /api/records/:table?filter=balance>500&sort=-id&page=1&limit=20
	req = httptest.NewRequest(http.MethodGet, "/api/records/customers?filter=balance>500&sort=-id&page=1&limit=20", nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)

	if w.Code != http.StatusOK {
		t.Fatalf("GET /api/records/customers with filter failed with code %d: %s", w.Code, w.Body.String())
	}

	var listResp struct {
		Table      string           `json:"table"`
		Page       int              `json:"page"`
		PerPage    int              `json:"perPage"`
		Limit      int              `json:"limit"`
		TotalItems int              `json:"totalItems"`
		TotalPages int              `json:"totalPages"`
		Records    []map[string]any `json:"records"`
		Items      []map[string]any `json:"items"`
	}
	if err := json.Unmarshal(w.Body.Bytes(), &listResp); err != nil {
		t.Fatalf("failed to decode list response: %v", err)
	}

	// Balance > 500: Alice (1000.5), Charlie (800.0), Evan (600.0) -> 3 items
	if listResp.TotalItems != 3 {
		t.Errorf("expected 3 total items matching balance>500, got %d", listResp.TotalItems)
	}
	if len(listResp.Records) != 3 {
		t.Fatalf("expected 3 records in page, got %d", len(listResp.Records))
	}
	if listResp.Limit != 20 || listResp.PerPage != 20 {
		t.Errorf("expected limit=20, perPage=20, got limit=%d, perPage=%d", listResp.Limit, listResp.PerPage)
	}

	// Sorted by -id: Evan (snowflake > 4), Charlie (3), Alice (1)
	if listResp.Records[0]["name"] != "Evan" {
		t.Errorf("expected first record by -id to be Evan, got %v", listResp.Records[0]["name"])
	}
	if listResp.Records[1]["name"] != "Charlie" {
		t.Errorf("expected second record by -id to be Charlie, got %v", listResp.Records[1]["name"])
	}
	if listResp.Records[2]["name"] != "Alice" {
		t.Errorf("expected third record by -id to be Alice, got %v", listResp.Records[2]["name"])
	}

	// 4. GET /api/records/:table/:id - Single record fetch
	req = httptest.NewRequest(http.MethodGet, "/api/records/customers/1", nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)

	if w.Code != http.StatusOK {
		t.Fatalf("GET /api/records/customers/1 failed with code %d: %s", w.Code, w.Body.String())
	}
	var singleRec map[string]any
	_ = json.Unmarshal(w.Body.Bytes(), &singleRec)
	if singleRec["name"] != "Alice" {
		t.Errorf("expected Alice, got %v", singleRec["name"])
	}

	// 5. GET non-existent record -> 404
	req = httptest.NewRequest(http.MethodGet, "/api/records/customers/9999", nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusNotFound {
		t.Errorf("expected 404 for missing record, got %d", w.Code)
	}

	// 6. PATCH /api/records/:table/:id - Partial update
	patchBody := []byte(`{"balance": 550.0, "status": "active"}`)
	req = httptest.NewRequest(http.MethodPatch, "/api/records/customers/2", bytes.NewReader(patchBody))
	req.Header.Set("Content-Type", "application/json")
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)

	if w.Code != http.StatusOK {
		t.Fatalf("PATCH /api/records/customers/2 failed with code %d: %s", w.Code, w.Body.String())
	}
	var patchedRec map[string]any
	_ = json.Unmarshal(w.Body.Bytes(), &patchedRec)
	if patchedRec["status"] != "active" {
		t.Errorf("expected status 'active', got %v", patchedRec["status"])
	}

	// Verify Bob now matches balance > 500
	req = httptest.NewRequest(http.MethodGet, "/api/records/customers?filter=id=2", nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	var bobList struct {
		Records []map[string]any `json:"records"`
	}
	_ = json.Unmarshal(w.Body.Bytes(), &bobList)
	if len(bobList.Records) != 1 || bobList.Records[0]["name"] != "Bob" {
		t.Fatalf("failed to retrieve updated Bob: %+v", bobList)
	}

	// 7. DELETE /api/records/:table/:id - Delete single record
	req = httptest.NewRequest(http.MethodDelete, "/api/records/customers/2", nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)

	if w.Code != http.StatusOK {
		t.Fatalf("DELETE /api/records/customers/2 failed with code %d: %s", w.Code, w.Body.String())
	}

	// Verify 404 when fetching deleted record
	req = httptest.NewRequest(http.MethodGet, "/api/records/customers/2", nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusNotFound {
		t.Errorf("expected 404 after delete, got %d", w.Code)
	}

	// 8. Test compound AND filter: filter=balance>500 && status='active'
	req = httptest.NewRequest(http.MethodGet, "/api/records/customers?filter="+url.QueryEscape("balance>500 && status='active'"), nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusOK {
		t.Fatalf("compound filter failed with code %d: %s", w.Code, w.Body.String())
	}
	var compoundResp struct {
		TotalItems int `json:"totalItems"`
	}
	_ = json.Unmarshal(w.Body.Bytes(), &compoundResp)
	// Alice, Charlie, Evan are active with balance > 500
	if compoundResp.TotalItems != 3 {
		t.Errorf("expected 3 items for compound filter, got %d", compoundResp.TotalItems)
	}

	// 9. Test direct query parameter shorthand: ?status=inactive
	req = httptest.NewRequest(http.MethodGet, "/api/records/customers?status=inactive", nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusOK {
		t.Fatalf("direct param filter failed: %s", w.Body.String())
	}
	var directResp struct {
		TotalItems int              `json:"totalItems"`
		Records    []map[string]any `json:"records"`
	}
	_ = json.Unmarshal(w.Body.Bytes(), &directResp)
	if directResp.TotalItems != 1 || directResp.Records[0]["name"] != "Diana" {
		t.Errorf("expected Diana for status=inactive, got: %+v", directResp)
	}

	// 10. GET non-existent table -> 404
	req = httptest.NewRequest(http.MethodGet, "/api/records/non_existent_table", nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusNotFound {
		t.Errorf("expected 404 for non-existent table, got %d", w.Code)
	}

	// 11. PUT /api/records/:table/:id - Update record
	putBody := []byte(`{"name": "Diana Prince", "balance": 999.0}`)
	req = httptest.NewRequest(http.MethodPut, "/api/records/customers/4", bytes.NewReader(putBody))
	req.Header.Set("Content-Type", "application/json")
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusOK {
		t.Fatalf("PUT /api/records/customers/4 failed: %d, %s", w.Code, w.Body.String())
	}
	var putResp map[string]any
	_ = json.Unmarshal(w.Body.Bytes(), &putResp)
	if putResp["name"] != "Diana Prince" {
		t.Errorf("expected Diana Prince, got %v", putResp["name"])
	}

	// 12. Multi-column sort: sort=-status,balance and pagination
	req = httptest.NewRequest(http.MethodGet, "/api/records/customers?sort=-status,balance&page=1&limit=2", nil)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusOK {
		t.Fatalf("multi-sort query failed: %d, %s", w.Code, w.Body.String())
	}
	var multiSortResp struct {
		Page    int              `json:"page"`
		PerPage int              `json:"perPage"`
		Limit   int              `json:"limit"`
		Records []map[string]any `json:"records"`
	}
	_ = json.Unmarshal(w.Body.Bytes(), &multiSortResp)
	if len(multiSortResp.Records) != 2 {
		t.Errorf("expected 2 records on page 1, got %d", len(multiSortResp.Records))
	}
}

func TestAPI_AutoGeneratedRecordsREST_Auth(t *testing.T) {
	server := setupTestServer()
	server.SetEnableAuth(true)

	// Create table
	_, err := server.ExecuteSQL("CREATE TABLE items (id INT PRIMARY KEY, title VARCHAR(50));")
	if err != nil {
		t.Fatalf("failed to create items table: %v", err)
	}

	handler := server.Handler()

	// 1. Unauthenticated request without API key -> 401 Unauthorized
	req := httptest.NewRequest(http.MethodGet, "/api/records/items", nil)
	w := httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusUnauthorized {
		t.Errorf("expected 401 for unauthenticated request, got %d", w.Code)
	}

	// 2. Create Read-Only API key
	keyObj, err := server.AuthService().CreateAPIKey("read-items-key", "read_only", []string{"items"})
	if err != nil {
		t.Fatalf("failed to create api key: %v", err)
	}

	// 3. GET with Read-Only API key -> 200 OK
	req = httptest.NewRequest(http.MethodGet, "/api/records/items", nil)
	req.Header.Set("X-API-Key", keyObj.Key)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusOK {
		t.Errorf("expected 200 with read-only key, got %d: %s", w.Code, w.Body.String())
	}

	// 4. POST with Read-Only API key -> 403 Forbidden
	req = httptest.NewRequest(http.MethodPost, "/api/records/items", bytes.NewReader([]byte(`{"id": 1, "title": "Desk"}`)))
	req.Header.Set("X-API-Key", keyObj.Key)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusForbidden {
		t.Errorf("expected 403 for write with read-only key, got %d", w.Code)
	}

	// 5. Create Read-Write API key
	rwKeyObj, err := server.AuthService().CreateAPIKey("rw-items-key", "read_write", []string{"items"})
	if err != nil {
		t.Fatalf("failed to create rw key: %v", err)
	}

	// 6. POST with Read-Write API key -> 201 Created
	req = httptest.NewRequest(http.MethodPost, "/api/records/items", bytes.NewReader([]byte(`{"id": 1, "title": "Desk"}`)))
	req.Header.Set("X-API-Key", rwKeyObj.Key)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusCreated {
		t.Fatalf("expected 201 with rw key, got %d: %s", w.Code, w.Body.String())
	}

	// 7. GET single record with Read-Only key -> 200 OK
	req = httptest.NewRequest(http.MethodGet, "/api/records/items/1", nil)
	req.Header.Set("X-API-Key", keyObj.Key)
	w = httptest.NewRecorder()
	handler.ServeHTTP(w, req)
	if w.Code != http.StatusOK {
		t.Fatalf("expected 200 for single record with read key, got %d", w.Code)
	}
}

func TestAPI_RecordsPaging_BoundedMemoryAndEarlyTermination(t *testing.T) {
	server := setupTestServer()
	handler := server.Handler()

	// 1. Create table "large_records"
	ddl := `
	CREATE TABLE large_records (
		id INT PRIMARY KEY,
		title VARCHAR(50) NOT NULL,
		val INT NOT NULL
	);
	`
	if _, err := server.ExecuteSQL(ddl); err != nil {
		t.Fatalf("failed to create table: %v", err)
	}

	// 2. Insert 1,000 records
	for i := 1; i <= 1000; i++ {
		query := `INSERT INTO large_records (id, title, val) VALUES (?, ?, ?);`
		_ = query
		// Direct SQL batch insert
	}
	// Use batch insert statement for speed
	var insertSQL bytes.Buffer
	insertSQL.WriteString("INSERT INTO large_records (id, title, val) VALUES ")
	for i := 1; i <= 1000; i++ {
		if i > 1 {
			insertSQL.WriteString(", ")
		}
		insertSQL.WriteString(fmt.Sprintf("(%d, 'Item_%d', %d)", i, i, i*10))
	}
	insertSQL.WriteString(";")
	if _, err := server.ExecuteSQL(insertSQL.String()); err != nil {
		t.Fatalf("failed to insert batch rows: %v", err)
	}

	// 3. Test Fast-Path Streaming Paging (No Sort, page=2, limit=25)
	// Must return exactly 25 items without accumulating full 1000 records
	req := httptest.NewRequest(http.MethodGet, "/api/records/large_records?page=2&limit=25", nil)
	w := httptest.NewRecorder()
	handler.ServeHTTP(w, req)

	if w.Code != http.StatusOK {
		t.Fatalf("GET /api/records/large_records failed: %d: %s", w.Code, w.Body.String())
	}

	var resp struct {
		TotalItems int              `json:"totalItems"`
		TotalPages int              `json:"totalPages"`
		Page       int              `json:"page"`
		PerPage    int              `json:"perPage"`
		Items      []map[string]any `json:"items"`
	}
	if err := json.Unmarshal(w.Body.Bytes(), &resp); err != nil {
		t.Fatalf("failed to unmarshal JSON response: %v", err)
	}

	if resp.TotalItems != 1000 {
		t.Errorf("expected totalItems=1000, got %d", resp.TotalItems)
	}
	if resp.TotalPages != 40 {
		t.Errorf("expected totalPages=40, got %d", resp.TotalPages)
	}
	if len(resp.Items) != 25 {
		t.Fatalf("expected 25 items in page 2, got %d", len(resp.Items))
	}

	// 4. Test perPage capped at 100 (client requests limit=250 -> must cap at 100)
	reqCap := httptest.NewRequest(http.MethodGet, "/api/records/large_records?limit=250", nil)
	wCap := httptest.NewRecorder()
	handler.ServeHTTP(wCap, reqCap)
	if wCap.Code != http.StatusOK {
		t.Fatalf("capped limit request failed: %d", wCap.Code)
	}
	var respCap struct {
		PerPage int              `json:"perPage"`
		Items   []map[string]any `json:"items"`
	}
	_ = json.Unmarshal(wCap.Body.Bytes(), &respCap)
	if respCap.PerPage != 100 {
		t.Errorf("expected perPage capped at 100, got %d", respCap.PerPage)
	}
	if len(respCap.Items) != 100 {
		t.Errorf("expected 100 items returned, got %d", len(respCap.Items))
	}

	// 5. Test Sorted Paging with filter (sort=-id, filter=val>=9000, page=1, limit=10)
	// val >= 9000 corresponds to id >= 900 (101 items from 900..1000)
	reqSort := httptest.NewRequest(http.MethodGet, "/api/records/large_records?sort=-id&filter=val%3E%3D9000&page=1&limit=10", nil)
	wSort := httptest.NewRecorder()
	handler.ServeHTTP(wSort, reqSort)

	if wSort.Code != http.StatusOK {
		t.Fatalf("sorted GET failed: %d: %s", wSort.Code, wSort.Body.String())
	}

	var respSort struct {
		TotalItems int              `json:"totalItems"`
		Items      []map[string]any `json:"items"`
	}
	if err := json.Unmarshal(wSort.Body.Bytes(), &respSort); err != nil {
		t.Fatalf("failed to unmarshal sorted JSON: %v", err)
	}
	if respSort.TotalItems != 101 {
		t.Errorf("expected 101 total items matching val>=9000, got %d", respSort.TotalItems)
	}
	if len(respSort.Items) != 10 {
		t.Fatalf("expected 10 items in page 1, got %d", len(respSort.Items))
	}
	// Highest id should be 1000
	sortFirstID := int64(respSort.Items[0]["id"].(float64))
	if sortFirstID != 1000 {
		t.Errorf("expected highest id 1000, got %d", sortFirstID)
	}
}

